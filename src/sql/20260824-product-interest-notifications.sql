  (category_key, category_score desc, confidence desc, last_signal_at desc);

create index if not exists product_notification_jobs_ready_idx
  on public.product_notification_jobs (available_at, id)
  where status in ('queued', 'retry');

create index if not exists product_notification_jobs_lease_idx
  on public.product_notification_jobs (locked_at, id)
  where status = 'processing';

create index if not exists customer_notification_deliveries_frequency_idx
  on public.customer_notification_deliveries (customer_id, channel, created_at desc)
  where status in ('pending', 'simulated', 'sent');

