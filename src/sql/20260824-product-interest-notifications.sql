create or replace function public.claim_product_notification_jobs(
  p_worker_id text,
  p_limit integer default 10,
  p_lease_seconds integer default 300
)
returns setof public.product_notification_jobs
language sql
security invoker
set search_path = ''
as $$
  with candidates as (
    select job.id
    from public.product_notification_jobs as job
    where job.attempts < job.max_attempts
      and (
        (
          job.status in ('queued', 'retry')
          and job.available_at <= now()
        )
        or (
          job.status = 'processing'
          and job.locked_at < now() - make_interval(secs => greatest(30, least(3600, p_lease_seconds)))
        )
      )
    order by job.available_at asc, job.id asc
    for update skip locked
    limit greatest(1, least(100, p_limit))
  )
  update public.product_notification_jobs as job
  set status = 'processing',
      attempts = job.attempts + 1,
      locked_at = now(),
      locked_by = left(coalesce(p_worker_id, 'unknown-worker'), 180),
      updated_at = now()
  from candidates
  where job.id = candidates.id
  returning job.*;
$$;

revoke execute on function public.claim_product_notification_jobs(text, integer, integer)
  from public, anon, authenticated;
grant execute on function public.claim_product_notification_jobs(text, integer, integer)
  to service_role;

create or replace function public.reserve_product_interest_delivery(
  p_campaign_id uuid,
  p_customer_id uuid,
  p_category_key text,
  p_match_score numeric,
  p_metadata jsonb,
  p_daily_cap integer,
  p_weekly_cap integer,
  p_dry_run boolean
)
returns uuid
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_delivery_id uuid;
  v_now timestamptz := now();
  v_daily_count integer := 0;
  v_weekly_count integer := 0;
  v_counted_statuses text[];
begin
  -- Serializa somente as reservas deste cliente/canal. Assim, campanhas
  -- diferentes processadas por workers distintos não ultrapassam os caps.
  perform pg_advisory_xact_lock(
    hashtextextended(p_customer_id::text || ':product-interest-email', 0)
  );

  if exists (
    select 1
    from public.customer_notification_deliveries as delivery
    where delivery.campaign_id = p_campaign_id
      and delivery.customer_id = p_customer_id
      and delivery.channel = 'email'
  ) then
    return null;
  end if;

  -- Simulação considera simulações anteriores para reproduzir os caps.
  -- Produção ignora simulações, mas conta reservas pendentes para evitar corrida.
  v_counted_statuses := case
    when coalesce(p_dry_run, false)
      then array['pending', 'simulated', 'sent']::text[]
    else array['pending', 'sent']::text[]
  end;

  if greatest(0, coalesce(p_daily_cap, 0)) > 0 then
    select count(*)::integer
    into v_daily_count
    from public.customer_notification_deliveries as delivery
    where delivery.customer_id = p_customer_id
      and delivery.channel = 'email'
      and delivery.status = any(v_counted_statuses)
      and delivery.created_at >= v_now - interval '24 hours';

    if v_daily_count >= greatest(0, p_daily_cap) then
      return null;
    end if;
  end if;

  if greatest(0, coalesce(p_weekly_cap, 0)) > 0 then
    select count(*)::integer
    into v_weekly_count
    from public.customer_notification_deliveries as delivery
    where delivery.customer_id = p_customer_id
      and delivery.channel = 'email'
      and delivery.status = any(v_counted_statuses)
      and delivery.created_at >= v_now - interval '7 days';

    if v_weekly_count >= greatest(0, p_weekly_cap) then
      return null;
    end if;
  end if;

  insert into public.customer_notification_deliveries (
    campaign_id,
    customer_id,
    channel,
    category_key,
    match_score,
    status,
    metadata,
    simulated_at,
    created_at,
    updated_at
  )
  values (
    p_campaign_id,
    p_customer_id,
    'email',
    left(p_category_key, 120),
    greatest(0, least(100, p_match_score)),
    case when coalesce(p_dry_run, false) then 'simulated' else 'pending' end,
    coalesce(p_metadata, '{}'::jsonb),
    case when coalesce(p_dry_run, false) then v_now else null end,
    v_now,
    v_now
  )
  on conflict (campaign_id, customer_id, channel) do nothing
  returning id into v_delivery_id;

  return v_delivery_id;
end;
$$;

