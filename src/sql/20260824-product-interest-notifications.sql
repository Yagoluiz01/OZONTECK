  from public, anon, authenticated;
grant execute on function public.suppress_customer_product_marketing(uuid, text)
  to service_role;

create or replace function public.enqueue_new_product_interest_campaign()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_campaign_id uuid;
  v_is_eligible boolean;
  v_was_eligible boolean := false;
begin
  v_is_eligible := lower(trim(coalesce(new.status, ''))) = 'active'
    and coalesce(new.stock_quantity, 0) > 0;

  if not v_is_eligible then
    return new;
  end if;

  if tg_op = 'UPDATE' then
    v_was_eligible := lower(trim(coalesce(old.status, ''))) = 'active'
      and coalesce(old.stock_quantity, 0) > 0;
    if v_was_eligible then
      return new;
    end if;
  end if;

  begin
    insert into public.product_notification_campaigns (
      product_id,
      campaign_type,
      product_snapshot,
      status
    )
    values (
      new.id,
      'new_product_interest',
      jsonb_build_object(
        'id', new.id,
        'name', new.name,
        'sku', new.sku,
        'category', new.category,
        'price', new.price,
        'status', new.status,
        'stock_quantity', new.stock_quantity,
        'image_url', new.image_url
      ),
      'queued'
    )
    on conflict (product_id, campaign_type) do nothing
    returning id into v_campaign_id;

    if v_campaign_id is not null then
      insert into public.product_notification_jobs (campaign_id, job_type, status)
      values (v_campaign_id, 'new_product_campaign', 'queued')
      on conflict (campaign_id, job_type) do nothing;
    end if;
  exception
    when others then
      -- A indisponibilidade do módulo de marketing nunca bloqueia o produto.
      raise warning 'OZONTECK product interest outbox failed for product %: %', new.id, sqlerrm;
  end;

  return new;
end;
$$;

revoke execute on function public.enqueue_new_product_interest_campaign()
  from public, anon, authenticated;

drop trigger if exists products_enqueue_new_interest_campaign
  on public.products;

create trigger products_enqueue_new_interest_campaign
after insert or update of status, stock_quantity on public.products
for each row
execute function public.enqueue_new_product_interest_campaign();

