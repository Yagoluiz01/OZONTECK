create or replace function public.suppress_customer_product_marketing(
  p_customer_id uuid,
  p_reason text default 'customer_unsubscribe'
)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
begin
  insert into public.customer_marketing_suppressions (
    customer_id,
    channel,
    reason,
    suppressed_at,
    updated_at
  )
  values (
    p_customer_id,
    'email',
    left(coalesce(nullif(trim(p_reason), ''), 'customer_unsubscribe'), 120),
    now(),
    now()
  )
  on conflict (customer_id, channel)
  do update set
    reason = excluded.reason,
    suppressed_at = excluded.suppressed_at,
    updated_at = excluded.updated_at;

  update public.customers
  set newsletter_opt_in = false,
      updated_at = now()
  where id = p_customer_id;
end;
$$;

