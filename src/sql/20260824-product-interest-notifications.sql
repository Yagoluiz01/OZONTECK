-- OZONTECK — notificações de novos produtos por interesse (backend-first).
-- Aplicar com as feature flags desativadas. O trigger apenas cria outbox;
-- nenhum e-mail é enviado dentro da transação de cadastro do produto.

begin;

create table if not exists public.customer_visitor_links (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references public.customers(id) on delete cascade,
  visitor_id text not null,
  last_session_id text,
  source text not null default 'authenticated_store',
  is_verified boolean not null default true,
  first_linked_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  profile_refreshed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint customer_visitor_links_visitor_length_chk
    check (char_length(visitor_id) between 1 and 180),
  constraint customer_visitor_links_session_length_chk
    check (last_session_id is null or char_length(last_session_id) between 1 and 180),
  constraint customer_visitor_links_source_length_chk
    check (char_length(source) between 1 and 60),
  constraint customer_visitor_links_customer_visitor_uk unique (customer_id, visitor_id),
  constraint customer_visitor_links_visitor_uk unique (visitor_id)
);

create table if not exists public.customer_interest_profiles (
  customer_id uuid not null references public.customers(id) on delete cascade,
  category_key text not null,
  category_label text not null,
  category_score numeric(5,2) not null,
  confidence numeric(5,2) not null,
  qualifying_signal_count integer not null default 0,
  signal_counts jsonb not null default '{}'::jsonb,
  last_signal_at timestamptz,
  profile_version text not null,
  calculated_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (customer_id, category_key),
  constraint customer_interest_profiles_category_key_length_chk
    check (char_length(category_key) between 1 and 120),
  constraint customer_interest_profiles_category_label_length_chk
    check (char_length(category_label) between 1 and 120),
  constraint customer_interest_profiles_category_score_chk
    check (category_score between 0 and 100),
  constraint customer_interest_profiles_confidence_chk
    check (confidence between 0 and 100),
  constraint customer_interest_profiles_qualifying_signals_chk
    check (qualifying_signal_count >= 0)
);

create table if not exists public.customer_marketing_suppressions (
  customer_id uuid not null references public.customers(id) on delete cascade,
  channel text not null default 'email',
  reason text not null default 'customer_unsubscribe',
  suppressed_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (customer_id, channel),
  constraint customer_marketing_suppressions_channel_chk
    check (channel in ('email')),
  constraint customer_marketing_suppressions_reason_length_chk
    check (char_length(reason) between 1 and 120)
);

create table if not exists public.product_notification_campaigns (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.products(id) on delete cascade,
  campaign_type text not null default 'new_product_interest',
  category_key text,
  product_snapshot jsonb not null default '{}'::jsonb,
  status text not null default 'queued',
  summary jsonb not null default '{}'::jsonb,
  last_error text,
  started_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint product_notification_campaigns_type_chk
    check (campaign_type in ('new_product_interest')),
  constraint product_notification_campaigns_status_chk
    check (status in ('queued', 'processing', 'completed', 'failed')),
  constraint product_notification_campaigns_product_type_uk
    unique (product_id, campaign_type)
);

create table if not exists public.product_notification_jobs (
  id bigint generated by default as identity primary key,
  campaign_id uuid not null references public.product_notification_campaigns(id) on delete cascade,
  job_type text not null default 'new_product_campaign',
  status text not null default 'queued',
  payload jsonb not null default '{}'::jsonb,
  attempts integer not null default 0,
  max_attempts integer not null default 3,
  available_at timestamptz not null default now(),
  locked_at timestamptz,
  locked_by text,
  last_error text,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint product_notification_jobs_type_chk
    check (job_type in ('new_product_campaign')),
  constraint product_notification_jobs_status_chk
    check (status in ('queued', 'processing', 'retry', 'completed', 'failed')),
  constraint product_notification_jobs_attempts_chk
    check (attempts >= 0 and max_attempts between 1 and 10),
  constraint product_notification_jobs_campaign_type_uk unique (campaign_id, job_type)
);

create table if not exists public.customer_notification_deliveries (
  id uuid primary key default gen_random_uuid(),
  campaign_id uuid not null references public.product_notification_campaigns(id) on delete cascade,
  customer_id uuid not null references public.customers(id) on delete cascade,
  channel text not null default 'email',
  category_key text not null,
  match_score numeric(5,2) not null,
  status text not null default 'pending',
  provider_message_id text,
  failure_reason text,
  metadata jsonb not null default '{}'::jsonb,
  sent_at timestamptz,
  simulated_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint customer_notification_deliveries_channel_chk
    check (channel in ('email')),
  constraint customer_notification_deliveries_status_chk
    check (status in ('pending', 'simulated', 'sent', 'skipped', 'failed')),
  constraint customer_notification_deliveries_match_score_chk
    check (match_score between 0 and 100),
  constraint customer_notification_deliveries_dedupe_uk
    unique (campaign_id, customer_id, channel)
);

create index if not exists customer_visitor_links_visitor_last_seen_idx
